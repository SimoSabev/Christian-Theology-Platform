export function getQuotesByTheme(theme: string): ChurchFatherQuote[] {
  return churchFatherQuotes.filter(q => q.themes.includes(theme));
}

export function getQuotesByAuthor(author: string): ChurchFatherQuote[] {
  return churchFatherQuotes.filter(q => q.author === author);
}

export function getQuotesByCentury(century: number): ChurchFatherQuote[] {
  return churchFatherQuotes.filter(q => q.century === century);
}

export function getQuoteOfDay(): ChurchFatherQuote {
  const today = new Date();
  const seed = today.getDate() + today.getMonth();
  const index = seed % churchFatherQuotes.length;
  return churchFatherQuotes[index]!;
}

